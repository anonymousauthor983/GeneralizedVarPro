"""Regression checks: known optima, ill conditioning, support changes, gradients."""
import json
import torch
import numpy as np
from core import solve_codes,lasso_active_refine,diagnostics
from check import check

def main():
    rng=np.random.RandomState(142);worst=0.;fallbacks=0
    for case in range(60):
        q,_=np.linalg.qr(rng.randn(16,16))
        h=q@np.diag(np.geomspace(1e-5,1,16))@q.T
        exact=rng.randn(16);exact[rng.rand(16)<.6]=0
        lam=10.**rng.uniform(-2,1)
        sub=np.where(exact!=0,np.sign(exact),rng.uniform(-.8,.8,16))
        b=h@exact+lam*sub
        initial=rng.randn(16)
        w,states=solve_codes(torch.tensor(h[None]),torch.tensor(b[None]),lam,
                            torch.tensor(initial[None]),max_sweeps=10)
        v=w.numpy()[0];st=states[0];worst=max(worst,st['kkt'])
        fallbacks+=int('fallback' in st)
        assert st['kkt']<=1e-8
        # Known optimum generated by the full convex KKT conditions.
        obj=lambda a:.5*a@h@a-b@a+lam*np.abs(a).sum()
        assert abs(obj(v)-obj(exact))<1e-7*max(1,abs(obj(exact)))
        assert np.max(np.abs(v-exact))<1e-4
    # Explicitly exercise removal of an incorrect active coefficient.
    h=np.array([[1.,.99999],[.99999,1.]])
    b=np.array([1.1,.99999]);w=np.array([.5,.5])
    st,steps=lasso_active_refine(h,b,w,.1,1e-8)
    assert np.allclose(w,[1.,0.],atol=1e-8),w
    gradient=check()
    result=dict(passed=True,known_optimum_cases=60,fallback_cases=fallbacks,
                worst_kkt=worst,boundary_steps=steps,gradient=gradient)
    print(json.dumps(result,indent=2))
    return result

if __name__=='__main__':main()
